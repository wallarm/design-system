/**
 * Generates src/lib/agent-characters/data.gen.ts from the handoff's data/*.json
 * (exported from the reference page, look v14, by the handoff's data/export.cjs).
 *
 *   pnpm agent-avatars:export          write the module
 *   pnpm agent-avatars:export --check  fail if the module is out of date
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { propDef } from '../../src/lib/agent-characters/props';

const here = path.dirname(fileURLToPath(import.meta.url));
const readJson = (name: string) =>
  JSON.parse(readFileSync(path.join(here, 'data', `${name}.json`), 'utf8'));
const OUT = path.resolve(here, '../../src/lib/agent-characters/data.gen.ts');

/** Builds the module text. `read` is injectable so tests can feed edited data. */
export function generate(read: typeof readJson = readJson): string {
  const shapes = read('shapes');
  const colors = read('colors');
  const eyes = read('eyes');
  const props = read('props');
  const cast = read('cast');
  const states = read('states');
  const optical = read('optical');
  const geomData = read('geom');
  // The geometry is measured on the page (capture-fixtures.ts); refuse to ship it for outlines it was not measured on.
  for (const sh of shapes.shapes as { id: string; d: string }[]) {
    const g = geomData.byShape[sh.id];
    if (!g || g.d !== sh.d)
      throw new Error(`geom.json is stale for ${sh.id}: recapture with capture-fixtures.ts`);
  }
  const extra = Object.keys(geomData.byShape).filter(
    id => !shapes.shapes.some((x: { id: string }) => x.id === id),
  );
  if (extra.length) throw new Error(`geom.json has shapes outside the kit: ${extra.join(', ')}`);
  const GEOMS = Object.fromEntries(
    Object.entries(
      geomData.byShape as Record<string, { top: number[]; HW: number[]; foot: number[] }>,
    ).map(([id, g]) => [id, { top: g.top, HW: g.HW, foot: g.foot }]),
  );

  const presets = cast.presets.map((p: Record<string, string | null>) => ({
    id: p.id,
    name: p.name,
    role: p.role,
    templateId: p.templateId ?? null,
    shape: p.shape,
    color: p.color,
    eyes: p.eyes,
    prop: p.prop,
  }));
  const OPTY = Object.fromEntries(
    Object.entries(optical.shapes as Record<string, { optY: number }>).map(([id, s]) => [
      id,
      s.optY,
    ]),
  );
  // The six presets' props as resolved data, so preset rendering ships no prop library (WDS-204, 07 §6.4).
  // propDef reads tones and geometry from the current data.gen.ts: after a tone or geometry change, export twice.
  const presetProps = Object.fromEntries(
    presets.map((p: { shape: string; color: string; prop: string }) => {
      const S = shapes.shapes.find((x: { id: string }) => x.id === p.shape);
      const hex = colors.colors.find((x: { id: string }) => x.id === p.color).hex;
      return [`${p.shape}|${hex}|${p.prop}`, propDef(p.prop, S, hex)];
    }),
  );
  const glyphProps = props.props
    .filter((p: { glyph: boolean }) => p.glyph)
    .map((p: { id: string }) => p.id);
  const j = (v: unknown) => JSON.stringify(v, null, 2);
  const ids = (list: string[]) => list.map(id => `'${id}'`).join(' | ');
  const shapeIds: string[] = shapes.shapes.map((x: { id: string }) => x.id);
  const colorIds: string[] = colors.colors.map((x: { id: string }) => x.id);
  const eyeIds = Object.keys(eyes.base);
  const propIds: string[] = props.props.map((x: { id: string }) => x.id);
  const castIds: string[] = cast.presets.map((x: { id: string }) => x.id);
  const toneIds = Object.keys(colors.tones.values);

  return `// GENERATED by scripts/agent-avatars/export-data.ts from the handoff data (reference look v14). Do not edit.
// Source export: ${shapes.$about.exported}

// Id unions: the page's own ids (07 §6.2). \`cyan\` is labelled «teal».
export type AgentShapeId = ${ids(shapeIds)};
export type AgentColorId = ${ids(colorIds)};
export type AgentEyeStyle = ${ids(eyeIds)};
export type AgentPropId = ${ids(propIds)};
export type AgentCharacterId = ${ids(castIds)};
export type AgentToneId = ${ids(toneIds)};

/** A stored look: four ids and a schema version, so a later kit change can migrate stored looks. */
export interface AgentLook {
  v: 1;
  shape: AgentShapeId;
  color: AgentColorId;
  eyes: AgentEyeStyle;
  prop: AgentPropId;
}

/** A preset: a look plus its default name, role and template (null: Wally, and Probe until its template exists). */
export interface AgentPreset extends Omit<AgentLook, 'v'> {
  id: AgentCharacterId;
  name: string;
  role: string;
  templateId: string | null;
}

export interface AgentShapeDef {
  id: AgentShapeId;
  fam: 'soft' | 'object';
  name: string;
  /** body outline on the 120-unit grid */
  d: string;
  /** visor [x, y, width, height] */
  v: [number, number, number, number];
  /** declared top anchor; otherwise measured */
  top?: [number, number];
  parts?: { d: string; tone: AgentToneId; z: 'b' | 'f' }[];
}
export interface AgentColorDef {
  id: AgentColorId;
  name: string;
  hex: string;
  g: 'brand' | 'cool' | 'warm' | 'pastel' | 'deep' | 'neutral';
  brand?: boolean;
}
export interface PropLayer {
  d: string;
  col: string;
  mat: 'vinyl' | 'felt' | null;
}
export interface PropDeco {
  s: string;
  clip?: boolean;
}
export interface PropDef {
  layers: PropLayer[];
  deco: PropDeco[];
  anim: { type: string; px: number; py: number } | null;
  fid: { k: string; px: number; py: number };
}
export interface EyeBase { w: number; ht: number; hb: number; kt: number; kb: number; lid: number }

export const SHAPE_IDS: AgentShapeId[] = ${j(shapeIds)};
export const COLOR_IDS: AgentColorId[] = ${j(colorIds)};
export const EYE_STYLES: AgentEyeStyle[] = ${j(eyeIds)};
export const PROP_IDS: AgentPropId[] = ${j(propIds)};

export const SHAPES: AgentShapeDef[] = ${j(shapes.shapes)};

export const COLORS: AgentColorDef[] = ${j(colors.colors)};

export const TONE: Record<AgentToneId, string> = ${j(colors.tones.values)};

export const HARD: ReadonlySet<string> = new Set(${j(colors.tones.hardTones)});

export const EYE_BASE: Record<AgentEyeStyle, EyeBase> = ${j(eyes.base)};

export const PROPS: [AgentPropId, string][] = ${j(props.props.map((p: { id: string; name: string }) => [p.id, p.name]))};

export const GLYPH_PROPS: ReadonlySet<string> = new Set(${j(glyphProps)});

export const CAST: AgentPreset[] = ${j(presets)};

/** propDef() for the six presets, keyed \`shape|hex|prop\`; any other look needs the AgentLookBuilder entry. */
export const PRESET_PROPS: Partial<Record<string, PropDef>> = ${j(presetProps)};

export const STATES: { key: string; label: string; product: string; engine: string }[] = ${j(states.states)};

export const SPRINGS: Record<string, { T: number; zeta: number }> = ${j(states.springs.values)};

export const OPTY: Record<AgentShapeId, number> = ${j(OPTY)};

/** geom() per shape as the page measures it (top anchor, half-width per row at y = i / 2, footprint at y 104). */
export const GEOMS: Record<AgentShapeId, { top: [number, number]; HW: number[]; foot: [number, number] }> = ${JSON.stringify(GEOMS)};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const out = generate();
  const rel = path.relative(process.cwd(), OUT);
  if (process.argv.includes('--check')) {
    if (readFileSync(OUT, 'utf8') !== out) {
      // biome-ignore lint/suspicious/noConsole: CLI output
      console.error(`${rel} is out of date: run pnpm agent-avatars:export`);
      process.exit(1);
    }
    // biome-ignore lint/suspicious/noConsole: CLI output
    console.log('agent-avatars data: up to date');
  } else {
    writeFileSync(OUT, out);
    // biome-ignore lint/suspicious/noConsole: CLI output
    console.log(`wrote ${rel}`);
  }
}
