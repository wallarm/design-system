/**
 * Measures where each preset's drawing sits in the 136 × 128 view box: the vertical middle of its idle pose
 * (body, parts and prop; no veil, no shadow), as the browser's getBBox reads it. `AgentAvatar align='drawing'`
 * centres that middle instead of the box. Run again whenever the artwork (data.gen.ts) changes:
 *
 *   pnpm tsx scripts/agent-avatars/measure-drawings.ts
 */

import type { BrowserType } from '@playwright/test';
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { charTree } from '../../src/lib/agent-characters/char';
import { CAST } from '../../src/lib/agent-characters/data.gen';
import { toSvgString } from '../../src/lib/agent-characters/svg';

const here = path.dirname(fileURLToPath(import.meta.url));
// Playwright is a dependency of the workspace's playwright-config, not of this package: borrow it from there.
const { chromium } = createRequire(
  path.resolve(here, '../../../configs/playwright-config/package.json'),
)('@playwright/test') as { chromium: BrowserType };
const OUT = path.resolve(here, '../../src/lib/agent-characters/drawing.gen.ts');

const browser = await chromium.launch();
const page = await browser.newPage();
const middles: Record<string, number> = {};
for (const p of CAST) {
  const t = charTree(p, { size: 56, state: 'idle', shadow: false, cover: false, ids: 'm' });
  await page.setContent(
    `<style>.veil,.veilr,image,defs{display:none}</style>${toSvgString('svg', { viewBox: '-8 -14 136 128' }, [{ tag: 'g', attrs: { id: 'drawing' }, children: t.children }])}`,
  );
  const { y, height } = await page.evaluate(() => {
    const box = (document.getElementById('drawing') as unknown as SVGGraphicsElement).getBBox();
    return { y: box.y, height: box.height };
  });
  middles[p.id] = Math.round((y + height / 2) * 10) / 10;
}
await browser.close();

writeFileSync(
  OUT,
  `// Generated by scripts/agent-avatars/measure-drawings.ts — do not edit.
import type { AgentCharacterId } from './data.gen';

/** The vertical middle of each preset's idle drawing in view-box units (the box's own middle is 50). */
export const DRAWING_MIDDLE: Record<AgentCharacterId, number> = ${JSON.stringify(middles, null, 2)};
`,
);
process.stdout.write(`${JSON.stringify(middles)}\n`);
